#!/usr/bin/env python3
"""xet-p2p vs rsync between two Modal sandboxes on a real ~100 GB Hugging Face dataset.

Method
------
- Dataset: FineWeb-Edu `sample/100BT` (HuggingFaceFW/fineweb-edu), Parquet shards of ~2.15 GB
  (already compressed). The first --shards shards (default 46, ~99 GB) are the dataset; the next
  --extra (default 5, ~11 GB) are what it grows by. Downloaded once into sandbox A from the Hub.
- Two sandboxes (debian_slim + rsync, 4 CPUs, 8 GiB, region us-east). A sends, B receives through
  B's raw TCP tunnels (Modal relays them; no UDP, so no QUIC): `xet-p2p serve` (TLS over TCP,
  pinned certificates from `xet-p2p keygen`) and an rsync daemon (unencrypted).
- Each tool runs the same sequence on its own destination, in a shuffled tool order:
    1. cold: the dataset into an empty destination (and, for xet-p2p, an empty receiver CAS)
    2. unchanged, first re-push (xet-p2p's receiver verifies its freshly installed files once)
    3. unchanged, steady state
    4. grown: --extra new shards added
    5. the same (grown) dataset into a second destination on the receiver
  Between steps the source settles for 3 s. Before step 5 the first destination is deleted (disk);
  this does not change what either tool must send to the second one.
- The source is a hard-linked view of the downloaded shards (no copy); xet-p2p's sender CAS starts
  empty for each tool run. `rsync -a` only: `-z` cannot shrink Parquet and would only cost CPU.
- Times are measured inside A. After steps 1, 4 and 5 the destination is verified by SHA-256 of
  every file on both sides.

Usage (needs the Modal SDK's Python and a Linux xet-p2p build):
    XET_P2P_AGENT_LINUX_BIN=target/x86_64-unknown-linux-musl/release/xet-p2p \\
    <modal-python> bench/s2s_dataset.py --out bench/results/s2s_dataset.md --raw bench/results/s2s_dataset.json
"""
import argparse
import json
import os
import random
import socket
import sys
import time
import urllib.request

REPO, SUBDIR = "HuggingFaceFW/fineweb-edu", "sample/100BT"
XET_PORT, RSYNC_PORT = 4434, 4435
X, K = "/opt/x/xet-p2p", "/opt/keys"
TOOLS = ["rsync -a", "xet-p2p"]
STEPS = ["cold", "unchanged (first re-push)", "unchanged (steady state)", "grown", "second destination"]
GIB = 1 << 30

DIGEST = "cd {0} && find . -type f -print0 | sort -z | xargs -0 -P4 -n4 sha256sum | sort -k2 | sha256sum | cut -c1-64"


def shard_names(n):
    url = f"https://huggingface.co/api/datasets/{REPO}/tree/main/{SUBDIR}"
    with urllib.request.urlopen(url, timeout=60) as r:
        files = sorted(f["path"] for f in json.load(r) if f.get("type") == "file")
    if len(files) < n:
        sys.exit(f"{REPO}/{SUBDIR} has only {len(files)} files")
    return files[:n]


def report(meta, runs, path):
    def row(step, tool):
        m = [r for r in runs if r["step"] == step and r["tool"] == tool]
        if not m:
            return "—", "—", "—"
        m = m[0]
        rate = m["data_bytes"] / m["wall"] / (1 << 20)
        sent = m["sent"] / GIB
        return f"{m['wall']:.0f} s", f"{sent:.2f} GiB" if sent >= 0.01 else f"{m['sent'] / 1024:.0f} KiB", f"{rate:.0f} MiB/s"

    out = [f"<!-- generated by bench/s2s_dataset.py; {json.dumps(meta)} -->", "",
           "| Step | " + " | ".join(f"{t} time | {t} sent" for t in TOOLS) + " |",
           "|---|" + "---:|---:|" * len(TOOLS)]
    for step in STEPS:
        cells = []
        for t in TOOLS:
            w, s, _ = row(step, t)
            cells += [w, s]
        out.append(f"| {step} | " + " | ".join(cells) + " |")
    out += ["", "xet-p2p details", "| Step | transfer (s) | connect (s) | files cached (sender) | files trusted (receiver) |",
            "|---|---:|---:|---:|---:|"]
    for step in STEPS:
        m = [r for r in runs if r["step"] == step and r["tool"] == "xet-p2p"]
        if m:
            m = m[0]
            out.append(f"| {step} | {m['transfer']:.0f} | {m['connect']:.1f} | {m['cached_files']} | {m['trusted']} |")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--raw", required=True)
    ap.add_argument("--shards", type=int, default=46)
    ap.add_argument("--extra", type=int, default=5)
    args = ap.parse_args()

    _gai = socket.getaddrinfo
    socket.getaddrinfo = lambda *a, **k: sorted(_gai(*a, **k), key=lambda i: i[0] != socket.AF_INET)
    import modal

    agent = os.environ.get("XET_P2P_AGENT_LINUX_BIN") or sys.exit("set XET_P2P_AGENT_LINUX_BIN")
    names = shard_names(args.shards + args.extra)
    base, extra = names[:args.shards], names[args.shards:]
    app = modal.App.lookup("xet-p2p-test", create_if_missing=True)
    image = modal.Image.debian_slim().apt_install("rsync").pip_install("huggingface_hub[hf_xet]")
    boxes, runs = [], []
    meta = {"repo": REPO, "subdir": SUBDIR, "shards": args.shards, "extra": args.extra}

    def sh(sb, cmd, t=4 * 3600):
        p = sb.exec("sh", "-c", cmd, timeout=t)
        out, err = p.stdout.read(), p.stderr.read()
        p.wait()
        if p.returncode != 0:
            raise RuntimeError(f"{cmd[:120]!r} failed ({p.returncode}): {err.strip()[-800:]}")
        return out.strip()

    def timed(sb, cmd):
        """Runs cmd in sb; returns (seconds measured inside the sandbox, stdout)."""
        out = sh(sb, f"s=$(date +%s.%N); {cmd} > /tmp/out.txt; e=$(date +%s.%N); "
                     "python3 -c \"import sys; print(float(sys.argv[2]) - float(sys.argv[1]))\" $s $e")
        return float(out.splitlines()[-1]), sh(sb, "cat /tmp/out.txt")

    try:
        for role in ("A", "B"):
            kw = {"unencrypted_ports": [XET_PORT, RSYNC_PORT]} if role == "B" else {}
            boxes.append(modal.Sandbox.create("sleep", "infinity", app=app, image=image, cpu=4.0, memory=8192,
                                              timeout=8 * 3600, region="us-east", **kw))
            print(f"sandbox {role} {boxes[-1].object_id} up", flush=True)
        a, b = boxes
        for sb in boxes:
            sh(sb, "mkdir -p /opt/x")
            sb.filesystem.copy_from_local(agent, X)
            sh(sb, f"chmod 755 {X}")
        sh(a, f"{X} keygen --out {K} --name client")
        sh(b, f"{X} keygen --out {K} --name server")
        a.filesystem.write_text(sh(b, f"cat {K}/server.crt") + "\n", f"{K}/server.crt")
        b.filesystem.write_text(sh(a, f"cat {K}/client.crt") + "\n", f"{K}/client.crt")
        tun = b.tunnels(timeout=60)
        xh, xp = tun[XET_PORT].tcp_socket
        rh, rp = tun[RSYNC_PORT].tcp_socket
        b.filesystem.write_text("[bench]\n  path = /recv/rsync\n  read only = false\n  use chroot = false\n"
                                "  uid = root\n  gid = root\n", "/tmp/rsyncd.conf")
        sh(b, "mkdir -p /recv/rsync")
        b.exec("rsync", "--daemon", "--no-detach", f"--port={RSYNC_PORT}", "--config=/tmp/rsyncd.conf")

        # Download once into A.
        a.filesystem.write_text(json.dumps(names), "/tmp/names.json")
        dl = ("python3 -c \"import json, time; from huggingface_hub import hf_hub_download; "
              "from concurrent.futures import ThreadPoolExecutor\n"
              "names = json.load(open('/tmp/names.json')); t = time.time()\n"
              f"get = lambda n: hf_hub_download('{REPO}', n, repo_type='dataset', local_dir='/data/hf')\n"
              "list(ThreadPoolExecutor(8).map(get, names)); print(time.time() - t)\"")
        secs = float(sh(a, dl).splitlines()[-1])
        size = int(sh(a, f"du -sb /data/hf/{SUBDIR} | cut -f1"))
        meta["download"] = {"bytes": size, "secs": secs}
        print(f"downloaded {size / 1e9:.1f} GB in {secs:.0f} s ({size / 1e6 / secs:.0f} MB/s)", flush=True)
        base_bytes = sum(int(sh(a, f"stat -c %s /data/hf/{n}")) for n in base)
        all_bytes = size

        def serve():
            sh(b, "for p in /proc/[0-9]*; do [ \"$(readlink $p/exe 2>/dev/null)\" = /opt/x/xet-p2p ] && kill ${p#/proc/}; done; "
                  "sleep 1; rm -rf /recv/cas /recv/xet /tmp/ready.json; mkdir -p /recv/xet; "
                  f"nohup {X} serve --no-quic --listen-tcp 0.0.0.0:{XET_PORT} --root /recv/xet --cas-dir /recv/cas "
                  f"--cert {K}/server.crt --key {K}/server.key --allow-client {K}/client.crt --ready-file /tmp/ready.json "
                  "> /tmp/serve.log 2>&1 < /dev/null & for i in $(seq 1 100); do [ -s /tmp/ready.json ] && exit 0; sleep 0.1; done; exit 1")

        def push(tool, dest):
            if tool == "rsync -a":
                w, out = timed(a, f"rsync -a --stats /work/src/ rsync://{rh}:{rp}/bench/{dest}/")
                num = lambda k: int(__import__("re").search(rf"Total (?:bytes )?{k}:\s*([\d,]+)", out).group(1).replace(",", ""))
                return {"wall": w, "sent": num("sent"), "transfer": w}
            w, out = timed(a, f"{X} push /work/src tcp://{xh}:{xp}/{dest} --cert {K}/client.crt --key {K}/client.key "
                              f"--peer-cert {K}/server.crt --cas-dir /work/cas --json")
            j = json.loads(out)
            return {"wall": w, "sent": j["udp_bytes_sent"], "transfer": j["elapsed_secs"], "connect": j["connect_secs"],
                    "cached_files": j["ingest"]["cached_files"], "trusted": j["receiver"]["files_trusted"]}

        def verify(tool, dest):
            remote = f"/recv/rsync/{dest}" if tool == "rsync -a" else f"/recv/xet/{dest}"
            assert sh(a, DIGEST.format("/work/src")) == sh(b, DIGEST.format(remote)), f"{tool} {dest}: tree differs"

        order = TOOLS[:]
        random.Random(1).shuffle(order)
        for tool in order:
            serve()
            sh(b, "rm -rf /recv/rsync/*")
            sh(a, "rm -rf /work && mkdir -p /work/src && " +
               " && ".join(f"ln /data/hf/{n} /work/src/{os.path.basename(n)}" for n in base))
            d1, d2 = f"{tool.split()[0]}-1", f"{tool.split()[0]}-2"
            for step in STEPS:
                time.sleep(3)
                if step == "grown":
                    sh(a, " && ".join(f"ln /data/hf/{n} /work/src/{os.path.basename(n)}" for n in extra))
                if step == "second destination":
                    sh(b, f"rm -rf /recv/rsync/{d1} /recv/xet/{d1}")
                dest = d2 if step == "second destination" else d1
                m = push(tool, dest)
                m.update({"tool": tool, "step": step,
                          "data_bytes": all_bytes if step in ("grown", "second destination") else base_bytes})
                if step in ("cold", "grown", "second destination"):
                    verify(tool, dest)
                runs.append(m)
                print(f"  {tool:9} {step:28} {m['wall']:7.0f} s  sent {m['sent'] / GIB:8.2f} GiB  "
                      f"({m['data_bytes'] / m['wall'] / (1 << 20):.0f} MiB/s of data)", flush=True)
                with open(args.raw, "w") as f:
                    json.dump({"meta": meta, "runs": runs}, f, indent=1)
                report(meta, runs, args.out)
            sh(b, "rm -rf /recv/rsync/* /recv/xet /recv/cas")
            sh(a, "rm -rf /work")
        print(f"wrote {args.out} and {args.raw}", flush=True)
    finally:
        for sb in boxes:
            try:
                sb.terminate()
                print(f"sandbox {sb.object_id} terminated", flush=True)
            except Exception as e:
                print(f"could not terminate {sb.object_id}: {e}", flush=True)


if __name__ == "__main__":
    main()
